/** Shared vectors in protocol/test-vectors — generated by the Swift implementation. */
class VectorTest {
    private fun vector(name: String): JsonObject =
        Json.parseObject(File(System.getProperty("airbridge.vectors"), "$name.json").readText())

    @Test fun pathVectors() {
        val v = vector("paths")
        for (c in v["cases"]!!.jsonArray) {
            val o = c.jsonObject
            val input = o["input"]!!.jsonPrimitive.content
            val expected = (o["expected"] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content
            assertEquals(expected, PathSanitizer.sanitize(input), "input: $input")
        }
        for (g in v["generated"]!!.jsonArray) {
            val o = g.jsonObject
            val s = o["component"]!!.jsonPrimitive.content.repeat(o["repeat"]!!.jsonPrimitive.int)
            assertEquals(o["valid"]!!.jsonPrimitive.content.toBoolean(), PathSanitizer.sanitize(s) != null, "len ${s.length}")
        }
    }

    @Test fun handshakeVectorsMatchSwift() {
        val v = vector("handshake")
        fun s(k: String) = v[k]!!.jsonPrimitive.content
        val b64 = Base64.getDecoder()
        val th = AbCrypto.transcriptHash(s("hello").toByteArray(), s("serverHello").toByteArray())
        assertEquals(s("transcriptHash"), AbCrypto.hex(th))

        // ECDH from the raw dialer scalar against the listener's SPKI (both directions agree).
        val ss = AbCrypto.ecdh(AbCrypto.privateKeyFromScalar(AbCrypto.unhex(s("dialerEphPrivate"))), b64.decode(s("listenerEphSpki")))
        assertEquals(s("sharedSecret"), AbCrypto.hex(ss))
        val ss2 = AbCrypto.ecdh(AbCrypto.privateKeyFromScalar(AbCrypto.unhex(s("listenerEphPrivate"))), b64.decode(s("dialerEphSpki")))
        assertContentEquals(ss, ss2)
        val keys = AbCrypto.deriveKeys(ss, th)
        assertEquals(s("keyDialerToListener"), AbCrypto.hex(keys.dialerToListener))
        assertEquals(s("keyListenerToDialer"), AbCrypto.hex(keys.listenerToDialer))
        assertEquals(s("sas"), AbCrypto.sas(th))

        val lid = b64.decode(s("listenerIdentitySpki"))
        val did = b64.decode(s("dialerIdentitySpki"))
        assertEquals(s("listenerFingerprint"), AbCrypto.hex(AbCrypto.fingerprint(lid)))
        assertEquals(s("listenerDeviceId"), AbCrypto.deviceId(lid))
        assertEquals(s("listenerDisplayFingerprint"), AbCrypto.displayFingerprint(lid))
        val code = s("pairingCode").toByteArray()
        assertEquals(s("listenerPairProof"), AbCrypto.hex(AbCrypto.hmac(code, AbCrypto.PAIR_LISTENER_LABEL, th, lid)))
        assertEquals(s("dialerPairProof"), AbCrypto.hex(AbCrypto.hmac(code, AbCrypto.PAIR_DIALER_LABEL, th, did)))
        // Swift (CryptoKit) signature verifies with JCA, and only for the right key.
        val sig = AbCrypto.unhex(s("serverAuthSignature"))
        assertTrue(AbCrypto.verify(lid, sig, AbCrypto.SERVER_AUTH_LABEL + th))
        assertFalse(AbCrypto.verify(did, sig, AbCrypto.SERVER_AUTH_LABEL + th))
        assertFalse(AbCrypto.verify(lid, sig, AbCrypto.CLIENT_AUTH_LABEL + th))

        // AES-GCM records are byte-identical across implementations.
        val enc = RecordCipher(keys.dialerToListener)
        val dec = RecordCipher(keys.dialerToListener)
        for (r in v["records"]!!.jsonArray) {
            val pt = AbCrypto.unhex(r.jsonObject["plaintext"]!!.jsonPrimitive.content)
            val ct = enc.seal(pt)
            assertEquals(r.jsonObject["ciphertext"]!!.jsonPrimitive.content, AbCrypto.hex(ct))
            assertContentEquals(pt, dec.open(ct))
        }
    }

    @Test fun recordTamperReorderReplayRejected() {
        val key = AbCrypto.randomBytes(32)
        val a = RecordCipher(key)
        val r0 = a.seal("one".toByteArray())
        val r1 = a.seal("two".toByteArray())
        assertFailsWith<Exception> { RecordCipher(key).open(r0.copyOf().also { it[0] = (it[0].toInt() xor 1).toByte() }) }
        assertFailsWith<Exception> { RecordCipher(key).open(r1) }
        val d = RecordCipher(key)
        assertContentEquals("one".toByteArray(), d.open(r0))
        assertFailsWith<Exception> { d.open(r0) }
    }

    @Test fun pairingCodeRules() {
        assertEquals("AB12CDE34F", PairingCode.normalize("ab12c-de34f"))
        assertEquals("0110011111", PairingCode.normalize("oIL00 11111"))
        assertNull(PairingCode.normalize("ABCDE-FGHJ"))
        assertNull(PairingCode.normalize("ABCDE-FGHJU"))
        val now = 1_000_000L
        val c = PairingCode(now = now)
        assertEquals(10, c.code.length)
        assertTrue(c.isUsable(now))
        assertFalse(c.isUsable(now + 301_000))
        repeat(5) { c.recordFailure() }
        assertFalse(c.isUsable(now))
        assertNotEquals(PairingCode().code, PairingCode().code)
    }

    @Test fun pairingUriRoundTripAndInterop() {
        val fp = AbCrypto.randomBytes(32)
        val u = PairingUri(listOf("172.20.10.2", "192.168.1.5"), 47820, "AB12CDE34F", fp, "Mahesh’s MacBook Air + test")
        assertEquals(u, PairingUri.parse(u.toUri()))
        // A URI produced by the Swift implementation (spaces as %20, '+' as %2B).
        val swift = "airbridge://pair?v=1&h=192.168.1.5,127.0.0.1&p=47820&c=AB12CDE34F&f=CIHhOm56PtzCSF9l1iiopE6nzpjrDjOwjXgBoeC4j8M&n=MacBook%20Air%20(test)%2B1"
        val p = PairingUri.parse(swift)!!
        assertEquals("MacBook Air (test)+1", p.name)
        assertEquals(listOf("192.168.1.5", "127.0.0.1"), p.hosts)
        assertNull(PairingUri.parse("airbridge://pair?v=2&h=1.2.3.4&p=1&c=AB12CDE34F"))
        assertNull(PairingUri.parse("airbridge://pair?v=1&h=1.2.3.4&p=0&c=AB12CDE34F"))
        assertNull(PairingUri.parse("airbridge://pair?v=1&h=1.2.3.4&p=1&c=AB12CDE34F&f=short"))
        assertNull(PairingUri.parse("https://evil.example/pair?v=1"))
    }

    @Test fun uniqueNames() {
        val existing = setOf("a.txt", "a (1).txt", ".bashrc", "noext")
        assertEquals("a (2).txt", PathSanitizer.uniqueName("a.txt") { it in existing })
        assertEquals(".bashrc (1)", PathSanitizer.uniqueName(".bashrc") { it in existing })
        assertEquals("noext (1)", PathSanitizer.uniqueName("noext") { it in existing })
    }

    @Test fun speedMeterUsesMeasuredBytesOnly() {
        val m = SpeedMeter(2_000)
        assertNull(m.current())
        m.add(0, 0); m.add(10_000_000, 1_000)
        assertEquals(10_000_000.0, m.current()!!, 1.0)
        m.add(30_000_000, 2_000); m.add(40_000_000, 4_000)
        assertEquals(5_000_000.0, m.current()!!, 1.0)
        assertEquals(10_000_000.0, m.average(4_000)!!, 1.0)
        assertEquals(2L, m.etaSeconds(50_000_000))
    }
}
